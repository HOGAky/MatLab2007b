function ds = charges_rhs(t,s,k,Q1,Q2,X1,Y1,X2,Y2,q3,q4,m3,m4)
x3 = s(1);
y3 = s(2);
vx3 = s(3);
vy3 = s(4);
x4 = s(5);
y4 = s(6);
vx4 = s(7);
vy4 = s(8);
dx = x3-X1;
dy = y3-Y1;
rr = max(sqrt(dx^2+dy^2),0.02)^3;
ax3 = k*q3*Q1*dx/rr;
ay3 = k*q3*Q1*dy/rr;
dx = x3-X2;
dy = y3-Y2;
rr = max(sqrt(dx^2+dy^2),0.02)^3;
ax3 = ax3+k*q3*Q2*dx/rr;
ay3 = ay3+k*q3*Q2*dy/rr;
dx = x3-x4;
dy = y3-y4;
rr = max(sqrt(dx^2+dy^2),0.02)^3;
ax3 = (ax3+k*q3*q4*dx/rr)/m3;
ay3 = (ay3+k*q3*q4*dy/rr)/m3;
dx = x4-X1;
dy = y4-Y1;
rr = max(sqrt(dx^2+dy^2),0.02)^3;
ax4 = k*q4*Q1*dx/rr;
ay4 = k*q4*Q1*dy/rr;
dx = x4-X2;
dy = y4-Y2;
rr = max(sqrt(dx^2+dy^2),0.02)^3;
ax4 = ax4+k*q4*Q2*dx/rr;
ay4 = ay4+k*q4*Q2*dy/rr;
dx = x4-x3;
dy = y4-y3;
rr = max(sqrt(dx^2+dy^2),0.02)^3;
ax4 = (ax4+k*q3*q4*dx/rr)/m4;
ay4 = (ay4+k*q3*q4*dy/rr)/m4;
ds = [vx3;vy3;ax3;ay3;vx4;vy4;ax4;ay4];
