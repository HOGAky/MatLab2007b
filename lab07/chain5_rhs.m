function ds = chain5_rhs(t,s,m,k)
x = s(1:5);
v = s(6:10);
a = zeros(5,1);
a(1) = (-k(1)*x(1)-k(2)*(x(1)-x(2)))/m(1);
a(2) = (k(2)*(x(1)-x(2))+k(3)*(x(3)-x(2)))/m(2);
a(3) = (-k(3)*(x(3)-x(2))-k(4)*(x(3)-x(4)))/m(3);
a(4) = (k(4)*(x(3)-x(4))+k(5)*(x(5)-x(4)))/m(4);
a(5) = (-k(5)*(x(5)-x(4))-k(6)*x(5))/m(5);
ds = [v;a];
