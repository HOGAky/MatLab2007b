function [px,py,pz,F] = rectpts(phi,l,b,c,a)
% Параллелепипед-маятник: ось вращения OO' - горизонтальная ось z,
% проходящая через точку O на расстоянии l от центра масс C (ось CC'
% параллельна OO'). a - размер вдоль оси, b и c - в плоскости качания.
cp = cos(phi);
sp = sin(phi);
% локальные координаты вершин относительно O (до поворота):
% центр масс C0 = (0,-l,0), размеры b(x), c(y), a(z)
dd = [ -b/2,  b/2,  b/2, -b/2, -b/2,  b/2,  b/2, -b/2 ];
ww = [ -c/2, -c/2,  c/2,  c/2, -c/2, -c/2,  c/2,  c/2 ];
hh = [ -a/2, -a/2, -a/2, -a/2,  a/2,  a/2,  a/2,  a/2 ];
x0 = dd;
y0 = -l+ww;
z0 = hh;
px = x0*cp - y0*sp;
py = x0*sp + y0*cp;
pz = z0;
F = [1 4 3 2; 5 6 7 8; 1 2 6 5; 2 3 7 6; 3 4 8 7; 4 1 5 8];
px = px(:).';
py = py(:).';
pz = pz(:).';
